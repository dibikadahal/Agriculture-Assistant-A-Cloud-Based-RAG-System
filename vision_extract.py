from dotenv import load_dotenv

load_dotenv()

# add the pdf file path
pdf_path = "data/Statistical_Nepalese_Agriculture.pdf"

# open the pdf
pdf = pdfium.PdfDocument(pdf_path)

# rendering page 14 (index 13) to an image
page = pdf[13]
image = page.render(scale = 2).to_pil() # scale = 2 -> higer resolution and sharper text
# .to_pil() coverts raw, low level data structure generated by pypdfium2 into a standard Python Imaging Library object
# Take this raw C++ computer bitmap data and wrap it into a standard Pillow Image object
# that Python libraries actually know how to interact with."


# save the image so we can see what actually does the model sees
image.save("images/page_14.png")
